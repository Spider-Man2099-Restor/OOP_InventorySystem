    private void logInBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_logInBtnActionPerformed
        String username = tfUsername.getText();
        String email = tfEmail.getText();
        String password = pfPassword.getText();

        LoginSignUpValidation validate = new LoginSignUpValidation();

        try {
            if (validate.validateLogin(username, email, password)) {
                Dashboard d = new Dashboard();
                this.dispose();
                d.setVisible(true);
            } else {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Invalid username, email, or password.",
                        "Login Failed",
                        javax.swing.JOptionPane.ERROR_MESSAGE
                );
            }
        } catch (IOException ex) {
            System.getLogger(LoginForm.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Error reading user data.",
                    "File Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_logInBtnActionPerformed

